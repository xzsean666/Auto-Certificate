#!/usr/bin/env bash
# ==============================================================================
# 示例 5: 证书自动化续期守护状态查看、模拟续期与日志审计
# 自动续期原理:
#   1. 安装后运行 `ngx-cert-manager timer setup` 会自动注册 Systemd Timer 守护定时器。
#   2. 每天固定在 03:30 和 15:30 自动执行一次续期扫描 (带 3600 秒随机时间抖动防并发冲击)。
#   3. 仅当证书剩余天数 <= 30 天时才会向 Let's Encrypt 申请续期。
#   4. 续期成功后会自动执行 `nginx -s reload` 平滑生效，全程零停机、零人工介入。
# ==============================================================================

set -euo pipefail

CMD="ngx-cert-manager"
if ! command -v ngx-cert-manager >/dev/null 2>&1; then
    CMD="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/ngx-cert-manager"
fi

echo "================================================================================"
echo ">>> [1/5] 查看所有受管证书大盘与剩余有效期 (🟢 正常 / 🟡 预警 / 🔴 紧急)..."
echo "================================================================================"
sudo "$CMD" cert list

echo ""
echo "================================================================================"
echo ">>> [2/5] 查看自动化续期守护定时器状态 (Systemd Timer / Cron)..."
echo "================================================================================"
sudo "$CMD" timer status

echo ""
echo "================================================================================"
echo ">>> [3/5] 模拟演练证书自动续期流程 (Dry-Run 测试，不消耗真实续期限额)..."
echo "================================================================================"
sudo "$CMD" cert renew --dry-run

echo ""
echo "================================================================================"
echo ">>> [4/5] 立即手动触发单次续期守护测试任务 (Trigger Now)..."
echo "================================================================================"
sudo "$CMD" timer trigger

echo ""
echo "================================================================================"
echo ">>> [5/5] 查看证书自动续期审计日志 (Audit Logs)..."
echo "================================================================================"
sudo "$CMD" timer logs
